#!/usr/bin/env python3
"""Builds the interactive panel preview of the project site (docs/demo).

The preview is the program's own panel: ui/index.html is copied to docs/demo/index.html with one extra
script in front of it (docs/demo/sim.js, written by hand), which answers the panel's requests from
made-up data. Run this from the repository root after every change in ui/:

    python3 tools/site_demo.py
"""
import os
import re
import shutil

src = open("ui/index.html", encoding="utf-8").read()
assert src.count("<script>") == 1, "expected exactly one inline script in ui/index.html"
version = re.search(r'var version = "([0-9.]+)"', open("engine.go", encoding="utf-8").read()).group(1)
head = "<!-- Generated by tools/site_demo.py from ui/index.html. Do not edit: change ui/index.html and run the tool. -->\n"
inject = '<script>window.LOOREK_VERSION = "%s";</script>\n<script src="sim.js"></script>\n<script>' % version
out = src.replace("<!doctype html>\n", "<!doctype html>\n" + head, 1).replace("<script>", inject, 1)

os.makedirs("docs/demo", exist_ok=True)
with open("docs/demo/index.html", "w", encoding="utf-8", newline="\n") as fh:
    fh.write(out)
shutil.copyfile("ui/icon.png", "docs/demo/icon.png")
if os.path.isdir("docs/demo/lang"):
    shutil.rmtree("docs/demo/lang")
shutil.copytree("ui/lang", "docs/demo/lang")
print("docs/demo built from ui/ (version %s)" % version)
